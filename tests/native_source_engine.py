"""Native Apple Silicon source build of the fixed upstream Noise engine.

The source and dependency lock are pinned, not a prebuilt executable digest.
The resulting binary is measured locally and used only in this runner.
"""
import hashlib
import os
from pathlib import Path
import platform
import subprocess
import tempfile

TARGET="aarch64-apple-darwin"

def build(directory, version, pin):
    if platform.system()!="Darwin" or platform.machine().lower()!="arm64":
        raise RuntimeError("native Apple Silicon runner required")
    def run(args, cwd, timeout=30):
        subprocess.run(args,cwd=cwd,check=True,timeout=timeout)
    def read(args,cwd):
        return subprocess.check_output(args,cwd=cwd,text=True,timeout=30).strip()
    toolchain=pin["rust_toolchain"]
    with tempfile.TemporaryDirectory(prefix="rathole-source-",dir=directory) as tmp:
        root=Path(tmp)
        run(["git","init","--quiet"],root)
        run(["git","remote","add","origin",pin["repository"]],root)
        run(["git","-c","protocol.file.allow=never","fetch","--depth=1","--no-tags","origin",pin["commit"]],root,90)
        if read(["git","rev-parse","FETCH_HEAD"],root)!=pin["commit"]:
            raise RuntimeError("upstream source commit differs")
        run(["git","checkout","--quiet","--detach",pin["commit"]],root)
        if read(["git","rev-parse","HEAD^{tree}"],root)!=pin["tree"]:
            raise RuntimeError("upstream source tree differs")
        if read(["git","hash-object","Cargo.lock"],root)!=pin["cargo_lock_blob"]:
            raise RuntimeError("upstream dependency lock differs")
        if read(["git","status","--porcelain","--untracked-files=no"],root):
            raise RuntimeError("upstream source modified before build")
        rust=read(["rustc","+"+toolchain,"-vV"],root)
        if "host: "+TARGET not in rust.splitlines() or not rust.startswith("rustc 1.79.0 "):
            raise RuntimeError("unexpected native source build compiler")
        # Old locked time 0.3.29 predates Rust 1.80 type-inference changes.
        # Do not silently update the upstream lock or enable unused transports.
        run(["cargo","+"+toolchain,"build","--release","--locked",
             "--target",TARGET,"--no-default-features","--features",pin["features"]],
            root,480)
        if read(["git","hash-object","Cargo.lock"],root)!=pin["cargo_lock_blob"] or read(
                ["git","status","--porcelain","--untracked-files=no"],root):
            raise RuntimeError("upstream source or lock changed during build")
        built=root/"target"/TARGET/"release"/"rathole"
        if not 0<built.stat().st_size<=64*1024*1024:
            raise RuntimeError("invalid built engine size")
        binary=built.read_bytes()
        if binary[:4]!=b"\xcf\xfa\xed\xfe" or int.from_bytes(binary[4:8],"little")!=0x0100000c:
            raise RuntimeError("built engine is not native ARM64 Mach-O")
        digest=hashlib.sha256(binary).hexdigest()
        path=directory/"rathole"
        with path.open("xb") as stream:
            stream.write(binary)
        path.chmod(0o700)
        if hashlib.sha256(path.read_bytes()).hexdigest()!=digest:
            raise RuntimeError("copied engine differs from native build")
        # No dependency or executable bytes are committed, and no secrets
        # have yet been generated by the calling real tunnel test.
        return path,{"version":version,"target":TARGET,
                     "source":pin["repository"],"source_commit":pin["commit"],
                     "source_tree":pin["tree"],"cargo_lock_blob":pin["cargo_lock_blob"],
                     "rust_toolchain":toolchain,"features":pin["features"],
                     "binary_bytes":len(binary),"binary_sha256":digest,
                     "pinned_source_and_lock_native_build_verified":True}
