//! Owner-only Unix agent configuration store.
//! Trusted ancestors and the current uid (including its other processes)
//! are part of the local trust boundary. Not encryption at rest or a keychain.
use std::fs::{self, DirBuilder, File, Metadata, OpenOptions};
use std::io::{Read, Write};
use std::net::SocketAddr;
use std::os::unix::fs::{DirBuilderExt, MetadataExt, OpenOptionsExt, PermissionsExt};
use std::path::{Component, Path, PathBuf};

const FILE: &str = "client.toml";
const MAX_CONFIG: u64 = 4096;
type Result<T> = std::result::Result<T, &'static str>;

extern "C" {
    fn geteuid() -> u32;
}
pub(crate) fn uid() -> u32 {
    // POSIX uid_t is u32 on the supported Linux and macOS targets.
    unsafe { geteuid() }
}

fn meta(path: &Path) -> Result<Metadata> {
    fs::symlink_metadata(path).map_err(|_| "agent store path unavailable")
}

pub(crate) fn trusted_path(path: &Path) -> Result<()> {
    if !path.is_absolute() {
        return Err("agent store requires an absolute path");
    }
    let owner = uid();
    let mut partial = PathBuf::new();
    for component in path.components() {
        match component {
            Component::RootDir | Component::Normal(_) => partial.push(component.as_os_str()),
            _ => return Err("invalid agent store path component"),
        }
        let m = meta(&partial)?;
        if !m.is_dir() || (m.uid() != 0 && m.uid() != owner) {
            return Err("untrusted agent store ancestor");
        }
        let mode = m.mode();
        // Root-owned sticky temporary directories protect entries against
        // different unprivileged uids. Other writable ancestors are rejected.
        if mode & 0o022 != 0 && !(m.uid() == 0 && mode & 0o1000 != 0) {
            return Err("writable agent store ancestor");
        }
    }
    Ok(())
}

pub(crate) fn private_dir(root: &Path) -> Result<()> {
    trusted_path(root)?;
    let m = meta(root)?;
    if m.uid() != uid() || m.mode() & 0o7777 != 0o700 {
        return Err("agent store must be owned by this uid with mode 0700");
    }
    Ok(())
}

pub fn init(root: &Path) -> Result<()> {
    let parent = root.parent().ok_or("agent store needs a parent")?;
    if !matches!(root.components().next_back(), Some(Component::Normal(_))) {
        return Err("invalid agent store directory");
    }
    trusted_path(parent)?;
    let p = meta(parent)?;
    if p.uid() != uid() || p.mode() & 0o022 != 0 {
        return Err("agent store parent must be owned and not group/world writable");
    }
    DirBuilder::new().mode(0o700).create(root).map_err(|_| "cannot create new agent store")?;
    if private_dir(root).is_err() {
        let _ = fs::remove_dir(root);
        return Err("cannot establish private agent store");
    }
    Ok(())
}

fn file_meta(m: &Metadata) -> Result<()> {
    if !m.is_file() || m.uid() != uid() || m.mode() & 0o7777 != 0o600
        || m.nlink() != 1 || !(1..=MAX_CONFIG).contains(&m.len()) {
        return Err("invalid private agent configuration file");
    }
    Ok(())
}

pub fn create(root: &Path, remote: &str, name: &str, local: SocketAddr, input: impl Read) -> Result<()> {
    private_dir(root)?;
    // Two newline-separated ASCII fields, token then server public key.
    // No environment fallback, command-line secret, or diagnostic echo.
    let mut raw = String::new();
    input.take(257).read_to_string(&mut raw).map_err(|_| "invalid agent credential input")?;
    if raw.len() > 256 {
        return Err("agent credential input too large");
    }
    let mut fields = raw.lines();
    let token = fields.next().ok_or("missing agent token")?;
    let key = fields.next().ok_or("missing server public key")?;
    if fields.next().is_some() {
        return Err("expected exactly two credential lines");
    }
    let config = crate::client_config(remote, name, local, token, key)?;
    let path = root.join(FILE);
    let mut file = OpenOptions::new().create_new(true).write(true).mode(0o600)
        .open(&path).map_err(|_| "cannot create new private agent configuration")?;
    let result = (|| {
        file.write_all(config.as_bytes()).and_then(|_| file.sync_all())
            .map_err(|_| "cannot write private agent configuration")?;
        file_meta(&file.metadata().map_err(|_| "agent configuration metadata unavailable")?)?;
        Ok(())
    })();
    if result.is_err() {
        drop(file);
        let _ = fs::remove_file(path);
    }
    result
}

fn value<'a>(line: Option<&&'a str>, prefix: &str) -> Result<&'a str> {
    line.and_then(|s| s.strip_prefix(prefix)).and_then(|s| s.strip_suffix('"'))
        .ok_or("invalid generated agent configuration")
}

fn validate_config(config: &str) -> Result<()> {
    // Only the canonical single-mapping config generated by this command
    // is accepted. Reject corrupted or manually inserted TOML directives.
    let lines: Vec<_> = config.lines().collect();
    if lines.len() != 16 {
        return Err("invalid generated agent configuration");
    }
    let remote = value(lines.get(1), "remote_addr = \"")?;
    let key = value(lines.get(10), "remote_public_key = \"")?;
    let name = lines[12].strip_prefix("[client.services.").and_then(|s| s.strip_suffix(']'))
        .ok_or("invalid generated agent configuration")?;
    let token = value(lines.get(14), "token = \"")?;
    let local = value(lines.get(15), "local_addr = \"")?.parse()
        .map_err(|_| "invalid generated agent configuration")?;
    let expected = crate::client_config(remote, name, local, token, key)
        .map_err(|_| "invalid generated agent configuration")?;
    if expected != config {
        return Err("invalid generated agent configuration");
    }
    Ok(())
}

pub fn checked_config(root: &Path) -> Result<PathBuf> {
    private_dir(root)?;
    let path = root.join(FILE);
    let before = meta(&path)?;
    file_meta(&before)?;
    let file = File::open(&path).map_err(|_| "cannot open private agent configuration")?;
    let after = file.metadata().map_err(|_| "agent configuration metadata unavailable")?;
    file_meta(&after)?;
    if before.dev() != after.dev() || before.ino() != after.ino() {
        return Err("agent configuration replaced while opening");
    }
    let mut config = String::new();
    file.take(MAX_CONFIG + 1).read_to_string(&mut config)
        .map_err(|_| "cannot read private agent configuration")?;
    if config.len() as u64 != after.len() {
        return Err("agent configuration size changed while reading");
    }
    validate_config(&config)?;
    Ok(path)
}
